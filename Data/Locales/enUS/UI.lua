-- Guard against inverted .toc order: guarantees enUS in the order.
do
    local want = "enUS"
    local found = false
    local n = table.getn(CM_LANG_ORDER)
    local i = 1
    while i <= n do
        if CM_LANG_ORDER[i] == want then
            found = true
        end
        i = i + 1
    end
    if not found then
        table.insert(CM_LANG_ORDER, want)
    end
end
