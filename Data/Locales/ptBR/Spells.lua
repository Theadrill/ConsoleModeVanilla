            return string.format("Aumenta %s do alvo em %s por %s min.", nomeAt, val, dur)
        end
    },
    -- Buffs de Armadura
    {
        pat = "^Increases armor by (%d+) for (%d+) min%.$",
        tpl = "Aumenta a armadura em %s por %s min."
    },
